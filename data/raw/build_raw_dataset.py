    out_path = os.path.join(out_dir, "raw_financials.csv")
    with open(out_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(COLUMNS)
        for row in RAW_ROWS:
            writer.writerow(row)
